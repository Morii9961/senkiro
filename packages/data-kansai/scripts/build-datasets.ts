import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { SkId, TrackSegment } from '@senkiro/contracts';
import { buildAtlasPmtiles, buildVerticalOdblPmtiles, KANSAI_BBOX } from '@senkiro/data-pipeline';
import { buildKansaiDataset } from './build-kansai.ts';
import { buildKantoPreviewDataset } from './build-kanto-preview.ts';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = path.resolve(__dirname, '..');
const TILES_DIR = path.join(PKG_ROOT, 'tiles');
const KANSAI_GEN_DIR = path.join(PKG_ROOT, 'src', 'kansai', 'generated');
const KANTO_GEN_DIR = path.join(PKG_ROOT, 'src', 'kanto-preview', 'generated');

mkdirSync(TILES_DIR, { recursive: true });
mkdirSync(KANSAI_GEN_DIR, { recursive: true });
mkdirSync(KANTO_GEN_DIR, { recursive: true });

function splitIntoChunks<T>(items: readonly T[], chunkCount: number): T[][] {
  const size = Math.ceil(items.length / chunkCount);
  const chunks: T[][] = [];
  for (let i = 0; i < chunkCount; i++) {
    chunks.push(items.slice(i * size, (i + 1) * size));
  }
  return chunks;
}

function writeSegmentsModule(
  dir: string,
  prefix: string,
  segments: readonly TrackSegment[],
  partCount: number,
): void {
  const chunks = splitIntoChunks(segments, partCount);
  const imports: string[] = [];
  const spreads: string[] = [];

  for (const [idx, chunk] of chunks.entries()) {
    const partNum = idx + 1;
    const fileName = `${prefix}-segments-${partNum}.ts`;
    const varName = `${prefix}SegmentsPart${partNum}`;
    writeFileSync(
      path.join(dir, fileName),
      `// Generated by scripts/build-datasets.ts — do not edit manually.\nimport type { TrackSegment } from '@senkiro/contracts';\n\nexport const ${varName}: TrackSegment[] = ${JSON.stringify(chunk, null, 2)};\n`,
      'utf8',
    );
    imports.push(`import { ${varName} } from './${fileName}';`);
    spreads.push(`...${varName}`);
  }

  writeFileSync(
    path.join(dir, `${prefix}-segments.ts`),
    `// Generated by scripts/build-datasets.ts — do not edit manually.\nimport type { TrackSegment } from '@senkiro/contracts';\n${imports.join('\n')}\n\nexport const ${prefix}Segments: TrackSegment[] = [\n  ${spreads.join(',\n  ')},\n];\n`,
    'utf8',
  );
}

function main(): void {
  // Remove legacy monolithic files if present
  rmSync(path.join(KANSAI_GEN_DIR, 'kansai-data.ts'), { force: true });
  rmSync(path.join(KANTO_GEN_DIR, 'kanto-data.ts'), { force: true });

  const kansai = buildKansaiDataset();
  const kanto = buildKantoPreviewDataset();

  // Kansai split (< 700 KB per file so Biome default 1 MiB maxSize stays warning-free)
  writeFileSync(
    path.join(KANSAI_GEN_DIR, 'kansai-stations.ts'),
    `// Generated by scripts/build-datasets.ts — do not edit manually.\nimport type { Station } from '@senkiro/contracts';\n\nexport const kansaiStations: Station[] = ${JSON.stringify(kansai.trackGraph.stations, null, 2)};\n`,
    'utf8',
  );
  writeSegmentsModule(KANSAI_GEN_DIR, 'kansai', kansai.trackGraph.segments, 4);
  writeFileSync(
    path.join(KANSAI_GEN_DIR, 'kansai-meta.ts'),
    `// Generated by scripts/build-datasets.ts — do not edit manually.\nimport type { ThroughService, TrackGraph } from '@senkiro/contracts';\nimport type { UnalignedRecord } from '@senkiro/domain-core';\nimport { kansaiSegments } from './kansai-segments.ts';\nimport { kansaiStations } from './kansai-stations.ts';\n\nexport const kansaiTrackGraph: TrackGraph = {\n  operators: ${JSON.stringify(kansai.trackGraph.operators, null, 2)},\n  lines: ${JSON.stringify(kansai.trackGraph.lines, null, 2)},\n  segments: kansaiSegments,\n  stations: kansaiStations,\n  complexes: ${JSON.stringify(kansai.trackGraph.complexes, null, 2)},\n  interchanges: ${JSON.stringify(kansai.trackGraph.interchanges, null, 2)},\n  sources: ${JSON.stringify(kansai.trackGraph.sources, null, 2)},\n};\n\nexport const kansaiThroughServices: readonly ThroughService[] = ${JSON.stringify(kansai.throughServices, null, 2)};\n\nexport const kansaiUnalignedRecords: readonly UnalignedRecord[] = ${JSON.stringify(kansai.unalignedRecords, null, 2)};\n`,
    'utf8',
  );

  // Kanto preview split (< 700 KB per file)
  writeFileSync(
    path.join(KANTO_GEN_DIR, 'kanto-stations.ts'),
    `// Generated by scripts/build-datasets.ts — do not edit manually.\nimport type { Station } from '@senkiro/contracts';\n\nexport const kantoStations: Station[] = ${JSON.stringify(kanto.trackGraph.stations, null, 2)};\n`,
    'utf8',
  );
  writeSegmentsModule(KANTO_GEN_DIR, 'kanto', kanto.trackGraph.segments, 2);
  writeFileSync(
    path.join(KANTO_GEN_DIR, 'kanto-meta.ts'),
    `// Generated by scripts/build-datasets.ts — do not edit manually.\nimport type { ThroughService, TrackGraph } from '@senkiro/contracts';\nimport type { UnalignedRecord } from '@senkiro/domain-core';\nimport { kantoSegments } from './kanto-segments.ts';\nimport { kantoStations } from './kanto-stations.ts';\n\nexport const kantoTrackGraph: TrackGraph = {\n  operators: ${JSON.stringify(kanto.trackGraph.operators, null, 2)},\n  lines: ${JSON.stringify(kanto.trackGraph.lines, null, 2)},\n  segments: kantoSegments,\n  stations: kantoStations,\n  complexes: ${JSON.stringify(kanto.trackGraph.complexes, null, 2)},\n  interchanges: ${JSON.stringify(kanto.trackGraph.interchanges, null, 2)},\n  sources: ${JSON.stringify(kanto.trackGraph.sources, null, 2)},\n};\n\nexport const kantoThroughServices: readonly ThroughService[] = ${JSON.stringify(kanto.throughServices, null, 2)};\n\nexport const kantoUnalignedRecords: readonly UnalignedRecord[] = ${JSON.stringify(kanto.unalignedRecords, null, 2)};\n`,
    'utf8',
  );

  writeFileSync(
    path.join(KANTO_GEN_DIR, 'kanto-vertical-odbl.ts'),
    `// Isolated ODbL 1.0 dataset generated by scripts/build-datasets.ts — NEVER merge into kantoTrackGraph.\nimport type { TrackVerticalLayer } from '@senkiro/contracts';\n\nexport const kantoVerticalLayer: TrackVerticalLayer = ${JSON.stringify(kanto.verticalLayer, null, 2)};\n`,
    'utf8',
  );

  const kansaiPmtiles = buildAtlasPmtiles({
    trackGraph: kansai.trackGraph,
    throughServices: kansai.throughServices,
    hubKeyByComplexId: new Map<SkId<'complex'>, 'umeda' | 'kyoto' | 'shinjuku'>([
      ['sk:complex:kansai:osaka-umeda', 'umeda'],
      ['sk:complex:kansai:kyoto', 'kyoto'],
    ]),
    bounds: KANSAI_BBOX,
    center: [135.58, 34.78, 10],
    minZoom: 6,
    maxZoom: 15,
    name: 'SENKIRO Kansai 8-Operator Railway Atlas',
    attribution: '国土数値情報 N02-24 (国土交通省) + SENKIRO Curated Registry',
  });
  writeFileSync(path.join(TILES_DIR, 'kansai-rail.pmtiles'), kansaiPmtiles);

  const kantoBounds: readonly [number, number, number, number] = [138.8, 35.0, 140.2, 36.1];
  const kantoPmtiles = buildAtlasPmtiles({
    trackGraph: kanto.trackGraph,
    throughServices: kanto.throughServices,
    hubKeyByComplexId: new Map<SkId<'complex'>, 'umeda' | 'kyoto' | 'shinjuku'>([
      ['sk:complex:kanto:shinjuku', 'shinjuku'],
    ]),
    bounds: kantoBounds,
    center: [139.7, 35.69, 10],
    minZoom: 6,
    maxZoom: 15,
    name: 'SENKIRO Kanto Preview Railway Atlas',
    attribution: '国土数値情報 N02-24 + 東京都交通局 GTFS',
  });
  writeFileSync(path.join(TILES_DIR, 'kanto-rail.pmtiles'), kantoPmtiles);

  const kantoVerticalPmtiles = buildVerticalOdblPmtiles({
    trackGraph: kanto.trackGraph,
    verticalLayer: kanto.verticalLayer,
    bounds: kantoBounds,
    center: [139.7, 35.69, 12],
    minZoom: 10,
    maxZoom: 15,
    name: 'SENKIRO Kanto Isolated ODbL Vertical Layer',
    attribution: '© OpenStreetMap contributors (ODbL 1.0)',
  });
  writeFileSync(path.join(TILES_DIR, 'kanto-rail-vertical.odbl.pmtiles'), kantoVerticalPmtiles);

  process.stdout.write(
    `[pmtiles] wrote:\n  - kansai-rail.pmtiles (${kansaiPmtiles.length} bytes)\n  - kanto-rail.pmtiles (${kantoPmtiles.length} bytes)\n  - kanto-rail-vertical.odbl.pmtiles (${kantoVerticalPmtiles.length} bytes)\n`,
  );
}

main();
