const linkLabels = new Map([
  ['通路', '步行至'],
  ['階段', '经楼梯前往'],
  ['エレベーター', '乘电梯前往'],
  ['エスカレーター', '乘扶梯前往'],
])

const characters: Record<string, string> = {
  線: '线', 環: '环', 東: '东', 鉄: '铁', 連: '联', 絡: '络',
  階: '层', 桜: '樱', 広: '广', 歩: '步', 図: '图', 側: '侧', 橋: '桥', 駅: '站', 貨: '货',
  戸: '户', 関: '关', 姫: '姬', 満: '满', '・': '·',
}

export function chineseName(ja: string): string {
  if (names[ja]) return names[ja]
  const [kind, target] = ja.split(' → ', 2)
  const action = linkLabels.get(kind)
  if (action && target) return action + ' ' + chineseName(target)
  return ja
    .replaceAll('うめきた', '梅北')
    .replace(/(\d+(?:・\d+)*)番のりば/g, '$1 号站台')
    .replace(/(\d+(?:・\d+)*)(?:番線|号線)(?:ホーム)?/g, '$1 号站台')
    .replace(/梅北 (\d+・\d+)番/g, '梅北 $1 号站台')
    .replaceAll('のりば', '站台')
    .replaceAll('ホーム', '站台')
    .replaceAll('改札口', '闸机')
    .replaceAll('改札', '闸机')
    .replaceAll('コンコース', '站厅')
    .replaceAll('エレベーター', '电梯')
    .replaceAll('エスカレーター', '扶梯')
    .replaceAll(' EV', ' 电梯')
    .replaceAll('乗降場', '电梯停靠处')
    .replaceAll('中2階', '2 层夹层')
    .replaceAll('横断歩道', '人行横道')
    .replace(/階段/g, '楼梯')
    .replace(/[線環東鉄連絡階桜広歩図側橋駅貨戸関姫満・]/g, (character) => characters[character])
}
