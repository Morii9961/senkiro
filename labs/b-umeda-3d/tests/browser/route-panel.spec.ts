import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
})

test('AT-NAV-01 and AT-NAV-03: the default route shows measured counts and honest grouped instructions', async ({ page }) => {
  await page.goto('/?lang=en&sf=1')
  const summary = page.getByTestId('route-summary')
  await expect(summary).toContainText(/8\s+Segments/)
  await expect(summary).toContainText(/2\s+Level changes/)
  await expect(summary).toContainText(/2\s+Gates/)
  await expect(summary).toContainText('Distance and duration: Unmeasured')
  const groups = page.getByTestId('route-step-group')
  await expect(groups).toHaveCount(2)
  await expect(groups.nth(0).getByRole('heading')).toHaveText('1F → B1F')
  await expect(groups.nth(1).getByRole('heading')).toHaveText('B1F → B2F')
  await expect(page.locator('[data-step-link]')).toHaveCount(8)
  await expect(page.locator('[data-step-link] [data-step-free="yes"]')).toHaveCount(8)
})

test('AT-NAV-02: picking a platform and a searched end fills the two route slots', async ({ page }) => {
  await page.goto('/?lang=en&sel=platform:sk:platform:jr-3-4')
  await page.getByTestId('detail-sheet').getByRole('button', { name: 'Start here' }).click()
  const from = page.getByTestId('route-from')
  const to = page.getByTestId('route-to')
  await expect(from).toContainText('Osaka platforms 3 / 4')
  await expect(from.locator('.line-badge')).toContainText('JR Kobe Line')
  await expect(from).toContainText('2F')
  await to.click()
  await page.getByRole('combobox', { name: 'Find a place' }).fill('Hankyu 3')
  await page.locator('[data-search-row="sk:platform:hk-3"]').getByRole('button', { name: /Set destination/ }).click()
  await expect(to).toContainText('Hankyu track 3')
  await expect(to.locator('.line-badge')).toContainText('Kyoto Line')
  await expect(to).toContainText('3F')
  await expect(page.getByTestId('route-summary')).toBeVisible()
  await page.getByRole('button', { name: 'Clear route' }).click()
  await expect(from).toContainText('Choose a place')
  await expect(to).toContainText('Choose a place')
  await page.reload()
  await expect(from).toContainText('Choose a place')
  await expect(page.getByTestId('route-summary')).toHaveCount(0)
})

test('AT-NAV-04: the same stairs-only walkway is drawn only with step-free mode disabled', async ({ page }) => {
  await page.goto('/?lang=en&from=sk:landing:foot-83&to=sk:landing:head-83')
  const canvas = page.locator('canvas')
  await page.getByRole('button', { name: /Start walkthrough/ }).click()
  await expect(canvas).toHaveAttribute('data-focus', 'sk:stairs:jr-83')
  await page.getByRole('checkbox', { name: 'Verified step-free links only' }).check()
  const failure = page.getByTestId('route-failure')
  await expect(failure).toHaveAttribute('data-blocker', 'stairs')
  await expect(failure).toHaveAttribute('data-link-id', 'sk:stairs:jr-83')
  await expect(failure).toContainText('Stairs')
  await expect(page.locator('[data-step-link]')).toHaveCount(0)
  await expect(canvas).toHaveAttribute('data-focus', '')
  await expect(canvas).not.toHaveAttribute('data-labels', /route-start|route-end/)
})
