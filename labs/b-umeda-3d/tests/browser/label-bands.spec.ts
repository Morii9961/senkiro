import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const messages: string[] = []
  errors.set(page, messages)
  page.on('pageerror', (error) => messages.push(error.message))
  page.on('console', (message) => {
    if (message.type() === 'error') messages.push(message.text())
  })
  await page.emulateMedia({ reducedMotion: 'reduce' })
})
test.afterEach(async ({ page }) => expect(errors.get(page)).toEqual([]))

test('AT-LBL-01: zoom reveals lines first and facilities later even on a large viewport', async ({ page }) => {
  await page.setViewportSize({ width: 2560, height: 1360 })
  await page.goto('/?lang=zh')
  const canvas = page.locator('canvas[data-triangles]')
  const lines = page.locator('.pin.lines-pin:visible')
  const platforms = page.locator('.pin.platform-pin:visible, .pin.cluster-pin:visible')
  await expect(canvas).toHaveAttribute('data-band', 'far')
  await expect(page.getByText('JR 大阪站·梅北地下站台', { exact: true })).toBeVisible()
  await expect(lines).toHaveCount(0)
  await expect(platforms).toHaveCount(0)
  const zoom = page.getByRole('button', { name: '放大', exact: true })
  await zoom.click()
  await zoom.click()
  await expect(canvas).toHaveAttribute('data-band', 'mid')
  await expect(lines.filter({ hasText: '东海道线' }).first()).toBeVisible()
  await expect(platforms).toHaveCount(0)
  await zoom.click()
  await zoom.click()
  await expect(canvas).toHaveAttribute('data-band', 'near')
  await expect(platforms.first()).toBeVisible()
  await expect(page.locator('.pin[data-label-level="4"]:visible').first()).toBeVisible()
  await expect(page.locator('.facility-pin')).toHaveCount(0)
  await expect(page.locator('.viewer-bar')).toHaveCount(0)
  await page.getByRole('button', { name: '重置视角', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-band', 'far')
  await expect(page.locator('.pin[data-label-level="3"]:visible, .pin[data-label-level="4"]:visible')).toHaveCount(0)
})

test('hovering over the station keeps label visibility and placement fixed', async ({ page }) => {
  await page.goto('/?lang=zh')
  const canvas = page.locator('canvas')
  await expect(canvas).toHaveAttribute('data-band', 'far')
  const station = page.locator('.station-pin').and(page.getByText('JR 大阪站', { exact: true }))
  await expect(station).toBeVisible()
  const box = (await station.boundingBox())!
  const placed = () => page.locator('.pin:visible').evaluateAll((pins) =>
    pins.map((pin) => [(pin as HTMLElement).dataset.key, (pin as HTMLElement).style.transform]),
  )
  const before = await placed()

  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await expect(page.locator('.scene')).toHaveCSS('cursor', 'pointer')
  expect(await placed()).toEqual(before)
  await page.mouse.move(box.x + box.width + 18, box.y + box.height / 2, { steps: 6 })
  expect(await placed()).toEqual(before)
})

test('3D floor focus keeps the camera and other floors as context', async ({ page }, info) => {
  await page.goto('/?lang=zh')
  const canvas = page.locator('canvas')
  await expect(canvas).toHaveAttribute('data-context-instances', '0')
  const before = await canvas.getAttribute('data-camera')
  const floors = page.getByRole('group', { name: '楼层', exact: true })
  const level = floors.getByRole('button', { name: '2F', exact: true })
  await level.click()
  await expect(canvas).toHaveAttribute('data-context-instances', /^[1-9]\d+$/)
  await expect(canvas).toHaveAttribute('data-camera', before!)
  await expect(level).toHaveAttribute('aria-pressed', 'true')
  const zoom = await page.getByRole('button', { name: '放大', exact: true }).boundingBox()
  expect((await level.boundingBox())!.y).toBeCloseTo(zoom!.y, 0)
  await page.screenshot({ path: info.outputPath('floor-context.png') })
  await page.reload()
  await expect(level).toHaveAttribute('aria-pressed', 'true')
  await expect(canvas).toHaveAttribute('data-context-instances', /^[1-9]\d+$/)
  await level.click()
  await expect(canvas).toHaveAttribute('data-context-instances', '0')
})
