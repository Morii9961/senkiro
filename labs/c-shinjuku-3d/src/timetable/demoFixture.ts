interface DemoPattern {
  station_id: string;
  operator_id: string;
  line_id: string;
  track: string;
  /** Minutes between trains — an arbitrary round number. */
  everyMin: number;
  /** Offset of the first train after the start of the pattern, minutes. */
  offsetMin: number;
  /** Seconds at the platform; null = the record has no arrival time, as in a departure-only station timetable. */
  dwellSec: number | null;
}

const FIRST_MIN = 5 * 60;
/** Runs past midnight on purpose: the fixture has to exercise times such as 24:35. */
const LAST_MIN = 24 * 60 + 40;

