/**
 * DEMO FIXTURE — not a timetable.
 *
 * Made-up departures at a fixed interval, generated here so that the train
 * animation can be exercised before the real timetable is handed over. No
 * time, trip or headway below is an operating fact, no record carries a train
 * number or a destination, and every id starts with "demo:". The interface
 * labels the whole simulation as a demo while this is in use, and the fixture
 * is dropped entirely — never merged — once a timetable is present.
 *
 * Only two things in it are not made up, because they do not come from the
 * fixture: which track a line uses (the station model) and the vehicle shown
 * (the vehicle library's rules, with their own sources).
 */
