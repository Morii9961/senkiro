const REMARK = 'DEMO FIXTURE: made-up time at a fixed interval, not a real departure.';

export function buildDemoRecords(): TimetableRecord[] {
  const records: TimetableRecord[] = [];
  for (const p of PATTERNS) {
    let n = 0;
    for (let min = FIRST_MIN + p.offsetMin; min <= LAST_MIN; min += p.everyMin) {
      n++;
      const depart = min * 60;
      records.push({
        station_id: p.station_id,
        operator_id: p.operator_id,
        line_id: p.line_id,
        platform_id: platformIdOf(p.station_id, p.track),
        direction_id: null,
        service_date_type: 'everyday',
        trip_id: `demo:${p.station_id}:${p.track}:${String(n).padStart(4, '0')}`,
        train_number: null,
        arrival_time_local: p.dwellSec == null ? null : formatServiceTime(depart - p.dwellSec, true),
        departure_time_local: formatServiceTime(depart, true),
        destination_text: null,
        service_class: null,
        // Left to the vehicle library's line rules; the fixture asserts nothing about vehicles.
        vehicle_series: null,
        formation_length: null,
        vehicle_assignment_status: 'unknown',
        source_id: DEMO_SOURCE_ID,
        valid_from: null,
        valid_until: null,
        remarks: REMARK,
      });
    }
  }
  return records;
}

let cached: TimetableDataset | null = null;

export function demoFixture(): TimetableDataset {
  cached ??= {
    kind: 'demo-fixture',
    label: 'Demo fixture',
    generatedAt: null,
    sources: [DEMO_SOURCE],
    records: buildDemoRecords(),
  };
  return cached;
}
